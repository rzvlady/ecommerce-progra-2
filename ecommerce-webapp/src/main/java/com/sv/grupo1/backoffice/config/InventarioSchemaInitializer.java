package com.sv.grupo1.backoffice.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.BeansException;
import org.springframework.beans.factory.config.BeanPostProcessor;
import org.springframework.stereotype.Component;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;

/**
 * Garantiza que la tabla core.movimientos_inventario exista en la base de datos
 * antes de la validación de esquema de Hibernate (ddl-auto=validate).
 */
@Component
public class InventarioSchemaInitializer implements BeanPostProcessor {

    private static final Logger LOG = LoggerFactory.getLogger(InventarioSchemaInitializer.class);

    private static final String SQL_CREATE_MOVIMIENTOS = """
            CREATE TABLE IF NOT EXISTS core.movimientos_inventario (
                id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                id_producto INTEGER NOT NULL,
                tipo_movimiento VARCHAR NOT NULL,
                cantidad INTEGER NOT NULL,
                motivo VARCHAR NOT NULL,
                fecha_movimiento TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                id_pedido INTEGER,
                CONSTRAINT fk_movimientos_to_productos FOREIGN KEY (id_producto) REFERENCES core.productos(id_producto)
            )
            """;

    @Override
    public Object postProcessAfterInitialization(Object bean, String beanName) throws BeansException {
        if (bean instanceof DataSource dataSource) {
            try (Connection conn = dataSource.getConnection();
                 Statement stmt = conn.createStatement()) {
                stmt.execute(SQL_CREATE_MOVIMIENTOS);
            } catch (Exception ex) {
                LOG.debug("Verificación inicial de core.movimientos_inventario omitida: {}", ex.getMessage());
            }
        }
        return bean;
    }
}
